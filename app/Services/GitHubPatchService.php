<?php

namespace App\Services;

use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;

class GitHubPatchService
{
    protected string $token;
    protected string $owner;
    protected string $repo;

    public function __construct()
    {
        $this->token = env('GITHUB_TOKEN', '');
        $this->owner = env('GITHUB_REPO_OWNER', '');
        $this->repo = env('GITHUB_REPO_NAME', '');
    }

    /**
     * Create an automated Hotfix Pull Request on GitHub.
     */
    public function createHotfixPullRequest(array $diagnosis): array
    {
        if (empty($this->token) || empty($this->owner) || empty($this->repo)) {
            return [
                'status' => 'skipped',
                'message' => 'GitHub credentials are not fully configured in .env'
            ];
        }

        $headers = [
            'Authorization' => "Bearer {$this->token}",
            'Accept' => 'application/vnd.github.v3+json',
            'User-Agent' => 'DevSentinel-Agent'
        ];

        try {
            // 1. Get the latest commit SHA of 'main' branch
            $refResponse = Http::withHeaders($headers)
                ->get("https://api.github.com/repos/{$this->owner}/{$this->repo}/git/ref/heads/main");

            if (!$refResponse->successful()) {
                return [
                    'status' => 'failed',
                    'error' => 'Failed to retrieve main branch ref: ' . $refResponse->body()
                ];
            }

            $mainSha = $refResponse->json('object.sha');
            $branchName = 'hotfix/error-' . time();

            // 2. Create a new hotfix branch
            $createBranchRes = Http::withHeaders($headers)
                ->post("https://api.github.com/repos/{$this->owner}/{$this->repo}/git/refs", [
                    'ref' => "refs/heads/{$branchName}",
                    'sha' => $mainSha
                ]);

            if (!$createBranchRes->successful()) {
                return [
                    'status' => 'failed',
                    'error' => 'Failed to create hotfix branch: ' . $createBranchRes->body()
                ];
            }

            // 3. Create or update a HOTFIX_NOTES.md in the repo with the AI diagnosis and patch
            $errorSummary = $diagnosis['error'] ?? 'Unknown Error';
            $file = $diagnosis['file'] ?? 'Unknown File';
            $line = $diagnosis['line'] ?? 0;
            $analysis = $diagnosis['analysis'] ?? [];
            $rootCause = $analysis['root_cause'] ?? 'N/A';
            $suggestedFix = $analysis['suggested_fix'] ?? 'N/A';
            $fixedCode = $analysis['fixed_code'] ?? '// See suggested fix';
            $severity = $analysis['severity'] ?? 'Medium';

            $patchContent = <<<MD
# 🚨 DevSentinel Automated Hotfix Report

- **Error:** `{$errorSummary}`
- **Target File:** `{$file}`
- **Failing Line:** `{$line}`
- **Severity Level:** `{$severity}`
- **Timestamp:** ` . date('Y-m-d H:i:s') . `

---

### 🔍 AI Root Cause Analysis
{$rootCause}

### 🛠️ Suggested Fix
{$suggestedFix}

### 💻 Proposed Corrected Code
```php
{$fixedCode}
```

---
*Generated automatically by DevSentinel Production Error Triage Engine.*
MD;

            // Commit this patch report to the new branch
            $patchFilePath = "hotfixes/hotfix-" . time() . ".md";
            $commitFileRes = Http::withHeaders($headers)
                ->put("https://api.github.com/repos/{$this->owner}/{$this->repo}/contents/{$patchFilePath}", [
                    'message' => "fix: automated AI hotfix patch for {$errorSummary}",
                    'content' => base64_encode($patchContent),
                    'branch' => $branchName
                ]);

            if (!$commitFileRes->successful()) {
                Log::warning('Could not commit hotfix file to branch: ' . $commitFileRes->body());
            }

            // 4. Create Pull Request
            $prTitle = "🤖 [DevSentinel Hotfix] Fix for: {$errorSummary} at line {$line}";
            $prBody = <<<MD
## 🚨 Production Error Intercepted by DevSentinel

A runtime exception occurred in the application and was automatically triaged by the **DevSentinel AI Engine**.

### 📋 Error Details:
- **Exception:** `{$errorSummary}`
- **File:** `{$file}`
- **Line:** `{$line}`
- **Severity:** `{$severity}`

### 🧠 AI Root Cause:
> {$rootCause}

### 🛠️ Proposed Solution:
{$suggestedFix}

```php
{$fixedCode}
```

---
*✅ Automatically generated by DevSentinel with GitHub API integration.*
MD;

            $prResponse = Http::withHeaders($headers)
                ->post("https://api.github.com/repos/{$this->owner}/{$this->repo}/pulls", [
                    'title' => $prTitle,
                    'head' => $branchName,
                    'base' => 'main',
                    'body' => $prBody
                ]);

            if ($prResponse->successful()) {
                $prUrl = $prResponse->json('html_url');
                return [
                    'status' => 'success',
                    'branch' => $branchName,
                    'pr_url' => $prUrl
                ];
            }

            return [
                'status' => 'failed',
                'error' => 'PR creation failed: ' . $prResponse->body()
            ];

        } catch (\Throwable $e) {
            Log::error('GitHubPatchService failed: ' . $e->getMessage());
            return [
                'status' => 'failed',
                'error' => $e->getMessage()
            ];
        }
    }
}
